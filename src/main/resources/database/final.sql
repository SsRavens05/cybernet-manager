-- 7. Trigger trừ điểm khi đổi quà
CREATE OR REPLACE TRIGGER trg_TruDiem_DoiQua
AFTER INSERT ON LICHSUDOIQUA
FOR EACH ROW
DECLARE
    v_diemtieuhao QUA_TANG.SODIEMTIEUHAO%TYPE;
    v_diemhientai KHACHHANG.SODIEMTICHLUY%TYPE;
BEGIN
    SELECT SODIEMTIEUHAO INTO v_diemtieuhao 
    FROM QUA_TANG 
    WHERE MAQT = :NEW.MAQT;

    SELECT SODIEMTICHLUY INTO v_diemhientai 
    FROM KHACHHANG 
    WHERE MAKH = :NEW.MAKH;

    IF NVL(v_diemhientai, 0) < (v_diemtieuhao * :NEW.SL) THEN
        RAISE_APPLICATION_ERROR(-20003, 'Lỗi: Khách hàng không đủ điểm tích lũy để đổi quà!');
    ELSE
        UPDATE KHACHHANG
        SET SODIEMTICHLUY = SODIEMTICHLUY - (v_diemtieuhao * :NEW.SL)
        WHERE MAKH = :NEW.MAKH;
    END IF;
END;
/

