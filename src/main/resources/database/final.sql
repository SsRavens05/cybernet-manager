-- R11: Mỗi ca làm có tối đa 5 nhân viên tham gia
CREATE OR REPLACE TRIGGER TRG_R11_MAX_NV_CALAM
BEFORE INSERT OR UPDATE ON CHI_TIET_CA_LAM
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM CHI_TIET_CA_LAM WHERE MACA = :NEW.MACA;
    IF v_count >= 5 THEN
        RAISE_APPLICATION_ERROR(-20011, 'Lỗi (R11): Mỗi ca làm chỉ có tối đa 5 nhân viên tham gia!');
    END IF;
END;
/

-- R16: Ngày nhập kho >= ngày vào làm của nhân viên
CREATE OR REPLACE TRIGGER TRG_R16_NGAYNHAP_NGAYVAOLAM
BEFORE INSERT OR UPDATE ON PHIEU_NHAP_KHO
FOR EACH ROW
DECLARE
    v_ngayvaolam DATE;
BEGIN
    SELECT NGAYVAOLAM INTO v_ngayvaolam FROM NHAN_VIEN WHERE MANV = :NEW.MANV;
    IF :NEW.NGAYNHAP < v_ngayvaolam THEN
        RAISE_APPLICATION_ERROR(-20016, 'Lỗi (R16): Ngày nhập kho phải lớn hơn hoặc bằng ngày vào làm của nhân viên!');
    END IF;
END;
/

-- R17: Mỗi khách hàng đang hoạt động chỉ được đổi tối đa 30 quà tặng
CREATE OR REPLACE TRIGGER TRG_R17_MAX_DOIQUA
BEFORE INSERT OR UPDATE ON LICHSUDOIQUA
FOR EACH ROW
DECLARE
    v_is_delete NUMBER;
    v_count NUMBER;
BEGIN
    SELECT IS_DELETE INTO v_is_delete FROM KHACHHANG WHERE MAKH = :NEW.MAKH;
    IF v_is_delete = 0 THEN
        SELECT COUNT(*) INTO v_count FROM LICHSUDOIQUA WHERE MAKH = :NEW.MAKH;
        IF v_count >= 30 THEN 
            RAISE_APPLICATION_ERROR(-20017, 'Lỗi (R17): Khách hàng đang hoạt động chỉ được đổi tối đa 30 lần!');
        END IF;
    END IF;
END;
/

-- R18: Một máy tính đang hoạt động chỉ được gắn tối đa 10 thiết bị
CREATE OR REPLACE TRIGGER TRG_R18_MAX_THIETBI
BEFORE INSERT OR UPDATE ON THIET_BI
FOR EACH ROW
DECLARE
    v_trangthai PC.TRANGTHAI%TYPE;
    v_count NUMBER;
BEGIN
    SELECT TRANGTHAI INTO v_trangthai FROM PC WHERE MAPC = :NEW.MAPC;
    IF UPPER(v_trangthai) = 'HOATDONG' OR UPPER(v_trangthai) = 'HOẠT ĐỘNG' THEN
        SELECT COUNT(*) INTO v_count FROM THIET_BI WHERE MAPC = :NEW.MAPC;
        IF v_count >= 10 THEN
            RAISE_APPLICATION_ERROR(-20018, 'Lỗi (R18): Máy tính đang hoạt động chỉ được gắn tối đa 10 thiết bị!');
        END IF;
    END IF;
END;
/

-- 1. Tự động tính Tổng Tiền Nhập Kho khi thêm Chi tiết nhập kho
CREATE OR REPLACE TRIGGER TRG_TINH_TONGTIEN_NHAPKHO
AFTER INSERT OR UPDATE ON CHI_TIET_NHAP_KHO
FOR EACH ROW
BEGIN
    UPDATE PHIEU_NHAP_KHO
    SET TONGTIENNHAP = NVL(TONGTIENNHAP, 0) + (:NEW.SOLUONGNHAP * :NEW.GIANHAP) + NVL(:NEW.CHIPHIKHAC, 0)
    WHERE MAPNK = :NEW.MAPNK;
END;
/

-- 2. Tự động tính Tổng Tiền Dịch Vụ khi khách gọi món
CREATE OR REPLACE TRIGGER TRG_TINH_TIEN_DICHVU
AFTER INSERT OR UPDATE ON DICH_VU_DA_DUNG
FOR EACH ROW
DECLARE
    v_dongia SAN_PHAM.DONGIABQ%TYPE;
BEGIN
    SELECT DONGIABQ INTO v_dongia FROM SAN_PHAM WHERE MASP = :NEW.MASP;
    
    UPDATE PHIEU_THANH_TOAN
    SET TONGSODV = NVL(TONGSODV, 0) + :NEW.SL,
        TONGTIENDV = NVL(TONGTIENDV, 0) + (:NEW.SL * v_dongia),
        TONGTIEN = NVL(TONGTIEN, 0) + (:NEW.SL * v_dongia)
    WHERE MALS = :NEW.MALS;
END;
/

-- 3. Đảm bảo Số máy của khu vực khớp với số lượng PC thực tế
CREATE OR REPLACE TRIGGER TRG_CAPNHAT_SOMAY_KHUVUC
AFTER INSERT OR DELETE ON PC
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        UPDATE KHUVUC SET SOMAYKV = NVL(SOMAYKV, 0) + 1 WHERE MAKV = :NEW.MAKV;
    ELSIF DELETING THEN
        UPDATE KHUVUC SET SOMAYKV = SOMAYKV - 1 WHERE MAKV = :OLD.MAKV;
    END IF;
END;
/

-- 4. Trigger cập nhật tồn kho khi nhập hàng
CREATE OR REPLACE TRIGGER trg_CapNhatTonKho_NhapHang
AFTER INSERT ON CHI_TIET_NHAP_KHO
FOR EACH ROW
DECLARE
    v_soluongtk_hientai SAN_PHAM.SOLUONGTK%TYPE;
    v_tensp             SAN_PHAM.TENSP%TYPE;
BEGIN
    SELECT SOLUONGTK, TENSP 
    INTO v_soluongtk_hientai, v_tensp
    FROM SAN_PHAM
    WHERE MASP = :NEW.MASP;

    IF :NEW.SOLUONGNHAP <= 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 
            'Loi: So luong nhap cho san pham [' || v_tensp || '] phai lon hon 0! ' ||
            '(So luong nhap hien tai: ' || :NEW.SOLUONGNHAP || ')');
    END IF;

    UPDATE SAN_PHAM
    SET SOLUONGTK = v_soluongtk_hientai + :NEW.SOLUONGNHAP
    WHERE MASP = :NEW.MASP;
END;
/

-- 5. Trigger trừ tồn kho khi bán hàng
CREATE OR REPLACE TRIGGER trg_CapNhatTonKho_BanHang
AFTER INSERT ON DICH_VU_DA_DUNG
FOR EACH ROW
DECLARE
    v_soluongtk SAN_PHAM.SOLUONGTK%TYPE;
BEGIN
    SELECT SOLUONGTK INTO v_soluongtk 
    FROM SAN_PHAM 
    WHERE MASP = :NEW.MASP;

    IF v_soluongtk < :NEW.SL THEN
        RAISE_APPLICATION_ERROR(-20002, 'Lỗi: Số lượng tồn kho không đủ để đáp ứng yêu cầu!');
    ELSE
        UPDATE SAN_PHAM
        SET SOLUONGTK = SOLUONGTK - :NEW.SL
        WHERE MASP = :NEW.MASP;
    END IF;
END;
/

-- 6. Trigger cộng điểm tích lũy khi thanh toán
CREATE OR REPLACE TRIGGER trg_CapNhatDiem_ThanhToan
AFTER INSERT ON PHIEU_THANH_TOAN
FOR EACH ROW
DECLARE
    v_makh KHACHHANG.MAKH%TYPE;
BEGIN
    BEGIN
        SELECT MAKH INTO v_makh
        FROM LICHSUCHOI
        WHERE MALS = :NEW.MALS;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_makh := NULL; 
    END;

    IF v_makh IS NOT NULL THEN
        UPDATE KHACHHANG
        SET SODIEMTICHLUY = NVL(SODIEMTICHLUY, 0) + FLOOR(NVL(:NEW.TONGTIEN, 0) / 1000)
        WHERE MAKH = v_makh;
    END IF;
END;
