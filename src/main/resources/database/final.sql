    PAR_MAPTT       IN PHIEU_THANH_TOAN.MAPTT%TYPE,
    PAR_MALS        IN PHIEU_THANH_TOAN.MALS%TYPE,
    PAR_TRANGTHAI   IN PHIEU_THANH_TOAN.TRANGTHAI%TYPE,
    TONGTIEN_OUT    OUT PHIEU_THANH_TOAN.TONGTIEN%TYPE,
    TONGTHOIGIAN_OUT OUT PHIEU_THANH_TOAN.TONGTHOIGIAN%TYPE,
    TONGSODV_OUT    OUT PHIEU_THANH_TOAN.TONGSODV%TYPE,
    TONGTIENDV_OUT  OUT PHIEU_THANH_TOAN.TONGTIENDV%TYPE
)
IS
    V_CountLS      NUMBER;
    V_CountPTT     NUMBER;
    V_NgayBD       LICHSUCHOI.NGAYBD%TYPE;
    V_NgayKT       LICHSUCHOI.NGAYKT%TYPE;
    V_MaPC         LICHSUCHOI.MAPC%TYPE;
    V_DonGia       LOAIKHUVUC.GIA%TYPE;
    V_TienGio      NUMBER := 0;
BEGIN
    SELECT COUNT(*) INTO V_CountLS FROM LICHSUCHOI WHERE MALS = PAR_MALS;

    IF V_CountLS = 0 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Lỗi: Không tồn tại phiên chơi này trong hệ thống!');
    END IF;

    SELECT COUNT(*) INTO V_CountPTT FROM PHIEU_THANH_TOAN WHERE MALS = PAR_MALS AND TRANGTHAI = 'Đã thanh toán' AND IS_DELETE = 0;

    IF V_CountPTT > 0 THEN
        RAISE_APPLICATION_ERROR(-20002, 'Lỗi: Phiên chơi này đã được thanh toán trước đó!');
    END IF;

    SELECT NGAYBD, NGAYKT, MAPC INTO V_NgayBD, V_NgayKT, V_MaPC FROM LICHSUCHOI WHERE MALS = PAR_MALS;

    IF V_NgayKT IS NULL THEN
        RAISE_APPLICATION_ERROR(-20003, 'Lỗi: Phiên chơi chưa kết thúc (Chưa đóng máy)!');
    END IF;

    TONGTHOIGIAN_OUT := ROUND((CAST(V_NgayKT AS DATE) - CAST(V_NgayBD AS DATE)) * 24 * 60);

    SELECT LKV.GIA INTO V_DonGia
    FROM PC P JOIN KHUVUC KV ON P.MAKV = KV.MAKV JOIN LOAIKHUVUC LKV ON KV.MALOAIKV = LKV.MALOAIKV
    WHERE P.MAPC = V_MaPC;

    V_TienGio := ROUND((TONGTHOIGIAN_OUT / 60) * V_DonGia);

    SELECT NVL(SUM(DV.SL), 0), NVL(SUM(DV.SL * SP.DONGIABQ), 0)
    INTO TONGSODV_OUT, TONGTIENDV_OUT
    FROM DICH_VU_DA_DUNG DV JOIN SAN_PHAM SP ON DV.MASP = SP.MASP
    WHERE DV.MALS = PAR_MALS AND DV.TRANGTHAI <> 'Đã hủy';

    TONGTIEN_OUT := V_TienGio + TONGTIENDV_OUT;

    INSERT INTO PHIEU_THANH_TOAN (
        MAPTT, MALS, TONGTIEN, TONGTHOIGIAN, TONGSODV, TONGTIENDV, TRANGTHAI, IS_DELETE, CREATE_AT
    )
    VALUES (
        PAR_MAPTT, PAR_MALS, TONGTIEN_OUT, TONGTHOIGIAN_OUT, TONGSODV_OUT, TONGTIENDV_OUT, PAR_TRANGTHAI, 0, CURRENT_TIMESTAMP
    );

    UPDATE PC SET TRANGTHAI = 'TRONG' WHERE MAPC = V_MaPC;
    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20004, 'Lỗi: Không tìm thấy dữ liệu hợp lệ để xử lý thanh toán!');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END CREATE_THANHTOAN;
/

