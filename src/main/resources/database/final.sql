-- INSERT_PHIEU_THANH_TOAN (Phiên bản tách rời)
CREATE OR REPLACE PROCEDURE INSERT_PHIEU_THANH_TOAN (
    PAR_MALS          PHIEU_THANH_TOAN.MALS%TYPE,
    PAR_TONGTIEN      PHIEU_THANH_TOAN.TONGTIEN%TYPE,
    PAR_TONGTHOIGIAN  PHIEU_THANH_TOAN.TONGTHOIGIAN%TYPE,
    PAR_TONGSODV     PHIEU_THANH_TOAN.TONGSODV%TYPE,
    PAR_TONGTIENDV    PHIEU_THANH_TOAN.TONGTIENDV%TYPE,
    PAR_TRANGTHAI     PHIEU_THANH_TOAN.TRANGTHAI%TYPE,
    MAPTT_OUT     OUT PHIEU_THANH_TOAN.MAPTT%TYPE
)
AS
    VAR_NEW_MAPTT VARCHAR2(50);
BEGIN
    VAR_NEW_MAPTT := 'PTT_' || TO_CHAR(SYSDATE, 'YYYYMMDD') || '_' || TO_CHAR(SYS_GUID());

    INSERT INTO PHIEU_THANH_TOAN (MAPTT, MALS, TONGTIEN, TONGTHOIGIAN, TONGSODV, TONGTIENDV, TRANGTHAI)
    VALUES (VAR_NEW_MAPTT, PAR_MALS, PAR_TONGTIEN, PAR_TONGTHOIGIAN, PAR_TONGSODV, PAR_TONGTIENDV, PAR_TRANGTHAI)
    RETURNING MAPTT INTO MAPTT_OUT;

    UPDATE LICHSUCHOI
    SET TRANGTHAI = 'Da thanh toan',
        NGAYKT = CURRENT_TIMESTAMP
    WHERE MALS = PAR_MALS;
    COMMIT;
END;
/

