-- 31. INSERT_CT_NHAPKHO (CÓ SỬ DỤNG SAVEPOINT)
CREATE OR REPLACE PROCEDURE INSERT_CT_NHAPKHO (
    PAR_MAPNK       IN VARCHAR2,
    PAR_MASP        IN VARCHAR2,
    PAR_LOAIHANG    IN VARCHAR2,
    PAR_SOLUONGNHAP IN NUMBER,
    PAR_GIANHAP     IN NUMBER,
    PAR_CHIPHIKHAC  IN NUMBER
) AS
    V_THANHTIEN NUMBER;
BEGIN
    SAVEPOINT truoc_khi_nhap_ct;

    V_THANHTIEN := PAR_SOLUONGNHAP * PAR_GIANHAP + NVL(PAR_CHIPHIKHAC, 0);

    INSERT INTO CHI_TIET_NHAP_KHO (MAPNK, MASP, LOAIHANG, SOLUONGNHAP, GIANHAP)
    VALUES (PAR_MAPNK, PAR_MASP, PAR_LOAIHANG, PAR_SOLUONGNHAP, PAR_GIANHAP);

    UPDATE PHIEU_NHAP_KHO
    SET TONGTIENNHAP = TONGTIENNHAP + V_THANHTIEN
    WHERE MAPNK = PAR_MAPNK;

    UPDATE_TONKHO(PAR_MASP, PAR_SOLUONGNHAP);
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK TO truoc_khi_nhap_ct;
        LOG_ERROR('INSERT_CT_NHAPKHO', SQLCODE, SQLERRM);
        RAISE;
END INSERT_CT_NHAPKHO;
/

