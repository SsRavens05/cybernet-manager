-- CONG_DIEM_TICHLUY (SERIALIZABLE + ERROR LOG)
CREATE OR REPLACE PROCEDURE CONG_DIEM_TICHLUY (
    PAR_MAKH KHACHHANG.MAKH%TYPE,
    PAR_DIEM_CONG NUMBER
)
AS
    VAR_DIEM_HIENTAI NUMBER;
BEGIN
    COMMIT; 
    SET TRANSACTION ISOLATION LEVEL SERIALIZABLE;

    SELECT SODIEMTICHLUY INTO VAR_DIEM_HIENTAI
    FROM KHACHHANG
    WHERE MAKH = PAR_MAKH;
    
    DBMS_SESSION.SLEEP(5);    
    
    UPDATE KHACHHANG
    SET SODIEMTICHLUY = VAR_DIEM_HIENTAI + PAR_DIEM_CONG
    WHERE MAKH = PAR_MAKH;
    
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        LOG_ERROR('CONG_DIEM_TICHLUY', SQLCODE, SQLERRM);
        RAISE;
END;
/

-- TRU_DIEM_DOIQUA (SERIALIZABLE + ERROR LOG)
CREATE OR REPLACE PROCEDURE TRU_DIEM_DOIQUA (
    PAR_MAKH KHACHHANG.MAKH%TYPE,
    PAR_DIEM_TRU NUMBER
