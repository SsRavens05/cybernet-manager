CREATE OR REPLACE FUNCTION F_CALC_TEMP_FEE(
    PAR_MALS IN LICHSUCHOI.MALS%TYPE
) RETURN NUMBER
IS
    V_NgayBD       LICHSUCHOI.NGAYBD%TYPE;
    V_MaPC         LICHSUCHOI.MAPC%TYPE;
    V_DonGia       LOAIKHUVUC.GIA%TYPE;
    V_ThoiGianChoi NUMBER;
    V_TienTamTinh  NUMBER := 0;
BEGIN
    SELECT NGAYBD, MAPC INTO V_NgayBD, V_MaPC
    FROM LICHSUCHOI
    WHERE MALS = PAR_MALS AND IS_DELETE = 0;
 
    SELECT LKV.GIA INTO V_DonGia
    FROM PC P
    JOIN KHUVUC KV ON P.MAKV = KV.MAKV
    JOIN LOAIKHUVUC LKV ON KV.MALOAIKV = LKV.MALOAIKV
    WHERE P.MAPC = V_MaPC
      AND P.IS_DELETE = 0 
      AND KV.IS_DELETE = 0 
      AND LKV.IS_DELETE = 0;
 
    V_ThoiGianChoi := ROUND((CAST(SYSTIMESTAMP AS DATE) - CAST(V_NgayBD AS DATE)) * 24 * 60);
 
    IF V_ThoiGianChoi > 0 THEN
        V_TienTamTinh := ROUND((V_ThoiGianChoi / 60) * V_DonGia);
    END IF;
 
    RETURN V_TienTamTinh;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RETURN 0;
    WHEN OTHERS THEN
        RETURN -1;
END F_CALC_TEMP_FEE;
/

