-- 25. END_SESSION_PC
CREATE OR REPLACE PROCEDURE END_SESSION_PC (
    PAR_MALS        IN  VARCHAR2,
    THOIGIAN_OUT    OUT NUMBER,
    TIENTAMTINH_OUT OUT NUMBER
) AS
    V_MAPC       VARCHAR2(50);
    V_NGAYBD     TIMESTAMP;
    V_GIA        NUMBER;
BEGIN
    SELECT MAPC, NGAYBD INTO V_MAPC, V_NGAYBD
    FROM LICHSUCHOI
    WHERE MALS = PAR_MALS;

    THOIGIAN_OUT := ROUND((CAST(SYSTIMESTAMP AS DATE) - CAST(V_NGAYBD AS DATE)) * 24 * 60);

    SELECT LKV.GIA INTO V_GIA
    FROM PC P
    JOIN KHUVUC KV   ON P.MAKV     = KV.MAKV
    JOIN LOAIKHUVUC LKV ON KV.MALOAIKV = LKV.MALOAIKV
    WHERE P.MAPC = V_MAPC;

    TIENTAMTINH_OUT := ROUND(THOIGIAN_OUT / 60 * V_GIA);

    UPDATE LICHSUCHOI
    SET NGAYKT    = SYSTIMESTAMP,
        TRANGTHAI = 'DAKET'
    WHERE MALS = PAR_MALS;

    UPDATE PC
    SET TRANGTHAI = 'TRONG'
    WHERE MAPC = V_MAPC;
    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END END_SESSION_PC;
